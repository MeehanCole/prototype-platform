/** 未登记的 key 退化为一个中性圆点，避免整块面板塌掉 */
export function NavIcon({ name, size = 12, color = '#1C5BD6', className }: { name: string; size?: number; color?: string; className?: string }) {
  const Comp = NAV_ICONS[name]
  if (!Comp) {
    return <X size={size} color="#B0B4BF" strokeWidth={1.6} className={className} />
  }
  return <Comp size={size} color={color} strokeWidth={1.8} className={className} />
}